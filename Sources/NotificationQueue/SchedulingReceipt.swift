import Foundation

/// Identity and scheduling state returned when saving an individual reminder.
/// A receipt confirms a verified queue pass, not delivery or immediate scheduling of every reminder.
public struct ReminderReceipt: Sendable {
    public let reminder: LocalReminder
    public var id: String { reminder.id }
    /// Inspect `lastOutcome` for whether this reminder is pending, deferred, or elapsed.
    public let journal: ReminderJournal
}

/// Identity and scheduling state returned when saving a batch.
public struct BatchReceipt: Sendable {
    public let batch: ReminderBatch
    public var id: String { batch.id }
    /// Inspect `lastOutcome` and `reminderDiagnostics` for individual scheduling results.
    public let journal: ReminderJournal
}

/// A batch operation failed; its ID remains available even when generated by the coordinator.
/// Retry the same ID or refresh saved intent rather than generating another batch.
public struct BatchSchedulingError: LocalizedError {
    public let batchID: String
    /// The original validation, persistence, authorization, scheduling, or cancellation error.
    public let underlyingError: any Error
    public var errorDescription: String? {
        "Batch \(batchID) could not finish scheduling: \(underlyingError.localizedDescription)"
    }
}
